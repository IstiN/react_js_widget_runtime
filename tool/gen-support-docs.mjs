#!/usr/bin/env node
// Generates docs/node-support.json and docs/dom-mapping.md from the mapping
// registry (SPECS + MAPPED_TYPES in src/dom/mapping.js — one source of
// truth: the mapping code) and the pinned kit's registered node types
// (docs/contract/nodes). Truthful by construction:
// - yes: the type is mapped in src/dom/mapping.js (real DOM, primary props
//   and events wired) and carries a SPECS entry (checked by the unit test)
// - partial + "host contract": the node needs a host surface the web
//   renderer only stubs or cannot embed (map, webView, three, scene3d, ...)
// - partial + "fallback": the fallback card renders (structure and node id
//   stay correct; string tap actions still fire)
// `node tool/gen-support-docs.mjs [--check]` (check: fail on drift, exit 1)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MAPPED_TYPES, SPECS } from '../src/dom/mapping.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const kitNodes = resolve(root, '.conformance', 'js_widget_runtime', 'docs', 'contract', 'nodes');
const check = process.argv.includes('--check');

// Host-surface types: the web renderer renders a stub surface (map) or only
// the fallback card; real content needs a host contract.
const HOST_CONTRACT = new Set(['map', 'webView', 'webview', 'three', 'scene3d', 'voxel', 'chart', 'flChart']);

const registered = readdirSync(kitNodes)
  .filter((name) => name.endsWith('.md'))
  .map((name) => name.replace(/\.md$/, ''))
  .sort();

const mapped = new Set(MAPPED_TYPES);
const support = {};
for (const type of registered) {
  if (HOST_CONTRACT.has(type)) {
    support[type] = mapped.has(type)
      ? { status: 'partial', reason: 'host contract', note: 'stub surface; taps and markers work, real content needs a host' }
      : { status: 'partial', reason: 'host contract' };
  } else if (mapped.has(type)) {
    support[type] = { status: 'yes' };
  } else {
    support[type] = { status: 'partial', reason: 'fallback' };
  }
}

const supportJson = JSON.stringify({ generatedFrom: 'src/dom/mapping.js + docs/contract/nodes', nodes: support }, null, 2) + '\n';

const FALLBACK_DOM = '<div> fallback card (dashed border, type name as text)';
const FALLBACK_CSS = 'fallback card + universal box and effect props';
const TAP_EVENTS = ['onTap ?? onPressed ?? onClick ?? onPress → click {}'];
const code = (s) => `\`${s}\``;

const rows = registered.map((type) => {
  const entry = support[type];
  const status = `${entry.status}${entry.reason ? ` (${entry.reason})` : ''}`;
  if (!mapped.has(type)) {
    return `| \`${type}\` | ${code(FALLBACK_DOM)} | \`data-node-id\`, \`data-node-type\` | ${FALLBACK_CSS} | ${TAP_EVENTS.join('; ')} | ${status} | fallback card; string tap actions fire |`;
  }
  const spec = SPECS[type];
  const attrs = ['data-node-id', 'data-node-type', ...(spec.attrs ?? [])];
  const notes = [entry.note, spec.notes].filter(Boolean).join('; ') || 'mapped — real DOM, primary props and events wired';
  return `| \`${type}\` | ${code(spec.dom)} | ${attrs.map(code).join(', ')} | ${spec.css} | ${(spec.events ?? ['—']).join('; ')} | ${status} | ${notes} |`;
});

const doc = `# DOM mapping

One row per registered node type (the contract inventory of
\`IstiN/js_widget_runtime\`). Generated by \`tool/gen-support-docs.mjs\` from
the mapping registry (\`SPECS\` + \`MAPPED_TYPES\` in \`src/dom/mapping.js\` —
one source of truth: the mapping code) and the pinned node pages; regenerate
and commit when the registry changes.

| Type | DOM structure | Attributes | CSS | Events | Status | Notes |
|---|---|---|---|---|---|---|
${rows.join('\n')}

Universal on every row:

- \`data-node-id="n<i>"\`, \`data-node-type="<type>"\` — the AUI dump walks
  exactly these elements (see \`src/dom/dumpViewTree.js\`). Interactive
  sub-elements (dropdown menu items, navigation destinations, map markers)
  carry no node id and are invisible to the dump, the way the reference dump
  keeps composite widgets as one node.
- React \`key\` = the widget \`key\` prop, falling back to the stable nodeId
  (reconciler identity).
- Effect props → CSS: \`opacity\`→opacity, \`blur\`→filter: blur(),
  \`clip\`→overflow: hidden, \`transform\` {perspective, rotateX, rotateY},
  \`offsetX\`/\`offsetY\`→translate, \`scale\`→scale, \`rotation\`→rotate.
- Box props → CSS: \`width\`/\`height\`, \`padding\`, \`margin\`,
  \`borderRadius\`, \`spacing\`→gap, \`decoration\` color/shadows/gradient →
  background/box-shadow, \`backgroundColor\` (and \`color\` as the background
  on non-text containers).
`;

if (check) {
  const currentJson = readFileSync(resolve(root, 'docs/node-support.json'), 'utf8');
  const currentDoc = readFileSync(resolve(root, 'docs/dom-mapping.md'), 'utf8');
  if (currentJson !== supportJson || currentDoc !== doc) {
    console.error('node-support/dom-mapping drifted from the registry — run `node tool/gen-support-docs.mjs` and commit');
    process.exit(1);
  }
  console.log(`node-support check: ${registered.length} types in sync`);
} else {
  writeFileSync(resolve(root, 'docs/node-support.json'), supportJson);
  writeFileSync(resolve(root, 'docs/dom-mapping.md'), doc);
  console.log(`generated docs for ${registered.length} registered types`);
}
