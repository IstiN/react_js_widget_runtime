#!/usr/bin/env node
// Generates docs/node-support.json and docs/dom-mapping.md from the mapping
// registry (MAPPED_TYPES) and the pinned kit's registered node types
// (docs/contract/nodes). Truthful by construction:
// - yes: the type is mapped in src/dom/mapping.js (real DOM, wired events)
// - partial + "host contract": the node needs a host surface the web
//   renderer only stubs or cannot embed (map, webView, three, scene3d, ...)
// - partial + "fallback": the fallback card renders (structure and node id
//   stay correct; string tap actions still fire)
// `node tool/gen-support-docs.mjs [--check]` (check: fail on drift, exit 1)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MAPPED_TYPES } from '../src/dom/mapping.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const kitNodes = resolve(root, '.conformance', 'js_widget_runtime', 'docs', 'contract', 'nodes');
const check = process.argv.includes('--check');

// Host-surface types: the web renderer renders a stub surface (map) or only
// the fallback card; real content needs a host contract.
const HOST_CONTRACT = new Set(['map', 'webView', 'webview', 'three', 'scene3d', 'voxel', 'chart', 'flChart']);

const registered = readdirSync(kitNodes)
  .filter((name) => name.endsWith('.md'))
  .map((name) => name.replace(/\.md$/, ''))
  .sort();

const mapped = new Set(MAPPED_TYPES);
const support = {};
for (const type of registered) {
  if (HOST_CONTRACT.has(type)) {
    support[type] = mapped.has(type)
      ? { status: 'partial', reason: 'host contract', note: 'stub surface; taps and markers work, real content needs a host' }
      : { status: 'partial', reason: 'host contract' };
  } else if (mapped.has(type)) {
    support[type] = { status: 'yes' };
  } else {
    support[type] = { status: 'partial', reason: 'fallback' };
  }
}

const supportJson = JSON.stringify({ generatedFrom: 'src/dom/mapping.js + docs/contract/nodes', nodes: support }, null, 2) + '\n';

const rows = registered.map((type) => {
  const entry = support[type];
  const detail = entry.status === 'yes'
    ? 'mapped — real DOM, primary props and events wired'
    : entry.status === 'partial' && entry.reason === 'host contract'
      ? 'stub surface or fallback card; real content needs a host contract'
      : 'fallback card (dashed border, type name, node id tag); string tap actions fire';
  return `| \`${type}\` | ${domStructure(type)} | \`data-node-id\`, \`data-node-type\` | ${cssSummary(type)} | ${entry.status}${entry.reason ? ` (${entry.reason})` : ''} | ${detail} |`;
});

const doc = `# DOM mapping

One row per registered node type (the contract inventory of
\`IstiN/js_widget_runtime\`). Generated by \`tool/gen-support-docs.mjs\` from
\`src/dom/mapping.js\` and the pinned node pages; regenerate and commit when
the registry changes.

| Type | DOM structure | Attributes | CSS | Status | Notes |
|---|---|---|---|---|---|
${rows.join('\n')}

Every mapped element carries \`data-node-id="n<i>"\` and
\`data-node-type="<type>"\`; the AUI dump walks exactly these elements
(see \`src/dom/dumpViewTree.js\`). Interactive sub-elements (dropdown menu
items, navigation destinations, map markers) carry no node id and are
invisible to the dump, the way the reference dump keeps composite widgets
as one node.
`;

if (check) {
  const currentJson = readFileSync(resolve(root, 'docs/node-support.json'), 'utf8');
  const currentDoc = readFileSync(resolve(root, 'docs/dom-mapping.md'), 'utf8');
  if (currentJson !== supportJson || currentDoc !== doc) {
    console.error('node-support/dom-mapping drifted from the registry — run `node tool/gen-support-docs.mjs` and commit');
    process.exit(1);
  }
  console.log(`node-support check: ${registered.length} types in sync`);
} else {
  writeFileSync(resolve(root, 'docs/node-support.json'), supportJson);
  writeFileSync(resolve(root, 'docs/dom-mapping.md'), doc);
  console.log(`generated docs for ${registered.length} registered types`);
}

function domStructure(type) {
  const tags = {
    text: '`<span>` (text child)', textButton: '`<button>`', button: '`<button>`',
    outlinedButton: '`<button>`', iconButton: '`<button>`', textField: '`<input>`',
    image: '`<img>`', video: '`<video controls>`', audio: '`<audio controls>`',
    center: '`<div>` flex center', column: '`<div>` flex column', row: '`<div>` flex row',
    scroll: '`<div>` overflow-y auto', listView: '`<div>` flex column, overflow-y auto',
    padding: '`<div>` box-sizing border-box', container: '`<div>`', card: '`<div>` radius+shadow',
    sizedBox: '`<div>` w/h', spacer: '`<div>` flex-grow 1', divider: '`<div>` 1px rule',
    icon: '`<span>` glyph child', gestureDetector: '`<div>` wheel+tap wiring',
    listTile: '`<div>` flex row, tap wiring', dropdown: '`<div>` menu component (open state is widget-local)',
    navigationBar: '`<div>` destination labels (clickable)', navigationRail: '`<div>` destination labels (clickable)',
    segmentedButton: '`<div>` segment labels (clickable)', map: '`<div>` stub surface + marker labels (clickable)',
  };
  return tags[type] ?? '`<div>` fallback card (type name as text)';
}

function cssSummary(type) {
  const families = {
    text: 'fontSize, color, fontWeight, textAlign, textShadows, effects',
    textField: 'box props + placeholder', textButton: 'box props',
    column: 'flex-direction column, gap=spacing, alignment', row: 'flex-direction row, gap=spacing, alignment',
    center: 'flex center', scroll: 'overflow-y auto', listView: 'flex column, overflow-y auto',
    map: 'background #dbeafe (stub)', image: 'box props', video: 'box props', audio: 'box props',
  };
  return families[type] ?? 'universal effect props (blur, clip, opacity, transform, shadows, gradients)';
}
